"""Bidirectional flow assembly (Phase 6).

Packets are grouped into flows using the classic 5-tuple, made direction-
agnostic so that both halves of a conversation land in the same flow:

    key = (min(endpoint_a, endpoint_b), max(endpoint_a, endpoint_b), protocol)

The direction of the very first packet defines "forward".

CICFlowMeter-compatible semantics
---------------------------------
CIC-IDS2017 was generated by CICFlowMeter, so this implementation deliberately
copies its rules rather than inventing new ones.  Where the tool's behaviour is
odd, it is still copied, because the model was trained on those values:

* a flow is closed once ``flow_timeout`` seconds (120 s) have passed **since it
  started**, not since its last packet (``FlowGenerator``:
  ``currentTimestamp - flow.getFlowStartTime() > flowTimeOut``);
* TCP flows also terminate on RST, or once FIN has been seen in **both**
  directions.  Research reports the 2017 tool closed on the first FIN and ignored
  RST, so this is a documented approximation of the published CSVs;
* single-packet flows are not emitted on the timeout or flush paths
  (``min_packets_to_emit``);
* the Active/Idle statistics use a 5 s threshold, and the final active burst is
  never recorded (the tool's ``endActiveIdleTime`` call is commented out);
* subflow breaks are counted on a 1 s gap, but see ``flow_to_features``: the
  published ``Subflow *`` columns equal the totals;
* packet-length statistics are computed over the **transport payload**, and
  their standard deviation/variance use the sample convention (``ddof=1``),
  matching Apache Commons ``SummaryStatistics``;
* the flow-wide length statistics count the **first packet twice**, because the
  tool adds it in both ``firstPacket`` and ``addPacket``;
* ``Fwd PSH/URG Flags`` only look at the first packet, and ``act_data_pkt_fwd``
  skips it;
* times are in **microseconds**, and the first packet seen defines "forward".

All per-flow statistics are accumulated incrementally (Welford), so a flow with
a million packets costs the same memory as a flow with three.
"""

from __future__ import annotations

import math
import threading
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Iterable

from src.utils.logger import get_logger

logger = get_logger(__name__)

TCP = 6
UDP = 17
ICMP = 1

FIN = 0x01
SYN = 0x02
RST = 0x04
PSH = 0x08
ACK = 0x10
URG = 0x20
ECE = 0x40
CWR = 0x80


@dataclass
class PacketInfo:
    """Protocol-independent view of one captured packet."""

    timestamp: float
    src_ip: str
    dst_ip: str
    src_port: int
    dst_port: int
    protocol: int
    payload_len: int = 0
    frame_len: int = 0
    header_len: int = 0
    flags: int = 0
    window: int = -1

    def endpoint_a(self) -> tuple[str, int]:
        return (self.src_ip, self.src_port)

    def endpoint_b(self) -> tuple[str, int]:
        return (self.dst_ip, self.dst_port)

    def flow_key(self) -> tuple:
        """Direction-agnostic flow key."""
        a, b = self.endpoint_a(), self.endpoint_b()
        return (a, b, self.protocol) if a <= b else (b, a, self.protocol)


class RunningStats:
    """Welford accumulator giving count/sum/min/max/mean/std/var."""

    __slots__ = ("n", "total", "minimum", "maximum", "_mean", "_m2")

    def __init__(self) -> None:
        self.n = 0
        self.total = 0.0
        self.minimum = 0.0
        self.maximum = 0.0
        self._mean = 0.0
        self._m2 = 0.0

    def add(self, value: float) -> None:
        value = float(value)
        self.n += 1
        self.total += value
        if self.n == 1:
            self.minimum = self.maximum = value
        else:
            self.minimum = min(self.minimum, value)
            self.maximum = max(self.maximum, value)
        delta = value - self._mean
        self._mean += delta / self.n
        self._m2 += delta * (value - self._mean)

    @property
    def mean(self) -> float:
        return self._mean if self.n else 0.0

    @property
    def variance(self) -> float:
        if self.n < 2:
            return 0.0
        return self._m2 / (self.n - 1)

    @property
    def std(self) -> float:
        return math.sqrt(max(0.0, self.variance))

    def as_dict(self) -> dict[str, float]:
        return {
            "count": float(self.n),
            "sum": self.total,
            "min": self.minimum if self.n else 0.0,
            "max": self.maximum if self.n else 0.0,
            "mean": self.mean,
            "std": self.std,
            "var": self.variance,
        }


@dataclass
class DirectionState:
    """Per-direction accumulators."""

    packets: int = 0
    bytes_total: int = 0
    header_bytes: int = 0
    min_header: float = 0.0
    psh_flags: int = 0
    urg_flags: int = 0
    data_packets: int = 0
    init_window: int = -1
    first_ts: float = 0.0
    last_ts: float = 0.0
    lengths: RunningStats = field(default_factory=RunningStats)
    iat: RunningStats = field(default_factory=RunningStats)
    fin_seen: bool = False


class Flow:
    """A single bidirectional network flow under construction."""

    ACTIVITY_THRESHOLD = 5.0   # seconds - CICFlowMeter activityTimeOut
    SUBFLOW_GAP = 1.0          # seconds - CICFlowMeter subflow separator

    def __init__(
        self,
        first_packet: PacketInfo,
        *,
        activity_threshold: float = 5.0,
        subflow_gap: float = 1.0,
    ) -> None:
        self.key = first_packet.flow_key()
        self.src_ip = first_packet.src_ip
        self.dst_ip = first_packet.dst_ip
        self.src_port = int(first_packet.src_port)
        self.dst_port = int(first_packet.dst_port)
        self.protocol = int(first_packet.protocol)

        self.activity_threshold = float(activity_threshold)
        self.subflow_gap = float(subflow_gap)

        self.first_ts = float(first_packet.timestamp)
        self.last_ts = float(first_packet.timestamp)
        self.packet_count = 0

        self.fwd = DirectionState()
        self.bwd = DirectionState()
        self.lengths = RunningStats()
        self.flow_iat = RunningStats()

        self.flag_counts: dict[str, int] = {
            "fin": 0, "syn": 0, "rst": 0, "psh": 0,
            "ack": 0, "urg": 0, "ece": 0, "cwr": 0,
        }

        self.subflow_count = 0
        self._subflow_last_ts = 0.0

        self.active = RunningStats()
        self.idle = RunningStats()
        self._start_active = float(first_packet.timestamp)
        self._end_active = float(first_packet.timestamp)

        self.terminated = False
        self.termination_reason = ""

        self.add(first_packet)

    # ------------------------------------------------------------- ingest
    def is_forward(self, packet: PacketInfo) -> bool:
        return packet.src_ip == self.src_ip and int(packet.src_port) == self.src_port

    def add(self, packet: PacketInfo) -> None:
        """Fold one packet into the flow's accumulators."""
        timestamp = float(packet.timestamp)
        forward = self.is_forward(packet)
        state = self.fwd if forward else self.bwd
        is_first = self.packet_count == 0

        if self.packet_count > 0:
            gap = max(0.0, timestamp - self.last_ts)
            self.flow_iat.add(gap * 1_000_000.0)
        self.packet_count += 1
        self.last_ts = max(self.last_ts, timestamp)

        payload = max(0, int(packet.payload_len))
        header = max(0, int(packet.header_len))

        if state.packets == 0:
            state.first_ts = timestamp
            state.min_header = float(header)
            if packet.protocol == TCP and packet.window is not None:
                state.init_window = int(packet.window)
        else:
            state.iat.add(max(0.0, timestamp - state.last_ts) * 1_000_000.0)
            state.min_header = min(state.min_header, float(header))
        state.last_ts = timestamp
        state.packets += 1
        state.bytes_total += payload
        state.header_bytes += header
        state.lengths.add(payload)
        # CICFlowMeter increments Act_data_pkt_forward in addPacket, which the
        # first packet never goes through.
        if payload > 0 and not is_first:
            state.data_packets += 1
        # L4 payload, not frame length.  The first packet goes into the flow-wide
        # statistics twice, as it does in CICFlowMeter's firstPacket + addPacket.
        self.lengths.add(payload)
        if is_first:
            self.lengths.add(payload)

        flags = int(packet.flags or 0)
        if packet.protocol == TCP and flags:
            if flags & FIN:
                self.flag_counts["fin"] += 1
                state.fin_seen = True
            if flags & SYN:
                self.flag_counts["syn"] += 1
            if flags & RST:
                self.flag_counts["rst"] += 1
                self.terminated = True
                self.termination_reason = "rst"
            if flags & PSH:
                self.flag_counts["psh"] += 1
                if is_first:  # fPSH_cnt is only updated in firstPacket
                    state.psh_flags += 1
            if flags & ACK:
                self.flag_counts["ack"] += 1
            if flags & URG:
                self.flag_counts["urg"] += 1
                if is_first:  # fURG_cnt is only updated in firstPacket
                    state.urg_flags += 1
            if flags & ECE:
                self.flag_counts["ece"] += 1
            if flags & CWR:
                self.flag_counts["cwr"] += 1

        self._update_subflow(timestamp)
        self._update_activity(timestamp)

        if self.fwd.fin_seen and self.bwd.fin_seen and not self.terminated:
            self.terminated = True
            self.termination_reason = "fin"

    def _update_subflow(self, timestamp: float) -> None:
        if self.subflow_count == 0:
            self.subflow_count = 1
            self._subflow_last_ts = timestamp
        elif (timestamp - self._subflow_last_ts) > self.subflow_gap:
            self.subflow_count += 1
        self._subflow_last_ts = timestamp

    def _update_activity(self, timestamp: float) -> None:
        if (timestamp - self._end_active) > self.activity_threshold:
            if (self._end_active - self._start_active) > 0:
                self.active.add((self._end_active - self._start_active) * 1_000_000.0)
            self.idle.add((timestamp - self._end_active) * 1_000_000.0)
            self._start_active = timestamp
            self._end_active = timestamp
        else:
            self._end_active = timestamp

    # ------------------------------------------------------------ queries
    @property
    def duration_seconds(self) -> float:
        return max(0.0, self.last_ts - self.first_ts)

    @property
    def duration_us(self) -> float:
        return self.duration_seconds * 1_000_000.0

    def is_expired(self, now: float, flow_timeout: float) -> bool:
        """True once ``flow_timeout`` seconds have passed since the flow *started*."""
        return (now - self.first_ts) > float(flow_timeout)

    def identity(self) -> dict[str, Any]:
        """The connection metadata stored with every prediction."""
        return {
            "src_ip": self.src_ip,
            "dst_ip": self.dst_ip,
            "src_port": self.src_port,
            "dst_port": self.dst_port,
            "protocol": self.protocol,
            "protocol_name": {TCP: "TCP", UDP: "UDP", ICMP: "ICMP"}.get(
                self.protocol, str(self.protocol)
            ),
            "start_time": self.first_ts,
            "end_time": self.last_ts,
            "duration_seconds": round(self.duration_seconds, 6),
            "packets": self.packet_count,
            "bytes": self.fwd.bytes_total + self.bwd.bytes_total,
            "termination": self.termination_reason or "timeout",
        }

    def __repr__(self) -> str:  # pragma: no cover - trivial
        return (
            f"<Flow {self.src_ip}:{self.src_port}->{self.dst_ip}:{self.dst_port} "
            f"proto={self.protocol} packets={self.packet_count}>"
        )


class FlowManager:
    """Groups packets into flows and emits them when they complete."""

    def __init__(
        self,
        *,
        flow_timeout: float = 120.0,
        activity_timeout: float = 5.0,
        subflow_timeout: float = 1.0,
        max_active_flows: int = 20000,
        on_flow_complete: Callable[[Flow], None] | None = None,
        min_packets_to_emit: int = 1,
    ) -> None:
        self.flow_timeout = float(flow_timeout)
        self.activity_timeout = float(activity_timeout)
        self.subflow_timeout = float(subflow_timeout)
        self.max_active_flows = int(max_active_flows)
        self.on_flow_complete = on_flow_complete
        self.min_packets_to_emit = int(min_packets_to_emit)

        self._flows: dict[tuple, Flow] = {}
        self._lock = threading.RLock()
        self.completed_count = 0
        self.packet_count = 0
        self.evicted_count = 0
        self.discarded_count = 0

    # -------------------------------------------------------------- ingest
    def add_packet(self, packet: PacketInfo) -> Flow | None:
        """Add a packet; returns a :class:`Flow` if that packet completed one."""
        key = packet.flow_key()
        completed: Flow | None = None
        with self._lock:
            self.packet_count += 1
            flow = self._flows.get(key)
            if flow is None:
                flow = Flow(
                    packet,
                    activity_threshold=self.activity_timeout,
                    subflow_gap=self.subflow_timeout,
                )
                self._flows[key] = flow
            else:
                if flow.is_expired(packet.timestamp, self.flow_timeout):
                    completed = self._close(key, "timeout")
                    flow = Flow(
                        packet,
                        activity_threshold=self.activity_timeout,
                        subflow_gap=self.subflow_timeout,
                    )
                    self._flows[key] = flow
                else:
                    flow.add(packet)

            if flow.terminated:
                finished = self._close(key, flow.termination_reason or "closed")
                if completed is None:
                    completed = finished
                elif finished is not None:
                    self._emit(finished)

            if len(self._flows) > self.max_active_flows:
                self._evict_oldest()

        if completed is not None:
            self._emit(completed)
        return completed

    # ------------------------------------------------------------- expiry
    def expire(self, now: float | None = None) -> list[Flow]:
        """Close every flow that has been idle for longer than the timeout."""
        now = time.time() if now is None else float(now)
        expired: list[Flow] = []
        with self._lock:
            for key in [
                k for k, f in self._flows.items() if f.is_expired(now, self.flow_timeout)
            ]:
                flow = self._close(key, "timeout")
                if flow is not None:
                    expired.append(flow)
        for flow in expired:
            self._emit(flow)
        return expired

    def flush(self) -> list[Flow]:
        """Close and emit every open flow (called when capture stops)."""
        with self._lock:
            keys = list(self._flows)
            flows = [f for f in (self._close(k, "flush") for k in keys) if f is not None]
        for flow in flows:
            self._emit(flow)
        return flows

    def _close(self, key: tuple, reason: str) -> Flow | None:
        flow = self._flows.pop(key, None)
        if flow is None:
            return None
        if not flow.termination_reason:
            flow.termination_reason = reason
        # CICFlowMeter guards its timeout and dump paths with packetCount() > 1, but
        # not its FIN and RST paths, so only flows closed by a flag bypass this.
        if not flow.terminated and flow.packet_count < self.min_packets_to_emit:
            self.discarded_count += 1
            return None
        self.completed_count += 1
        return flow

    def _evict_oldest(self) -> None:
        """Safety valve so a scan storm cannot exhaust memory."""
        if not self._flows:
            return
        oldest_key = min(self._flows, key=lambda k: self._flows[k].last_ts)
        flow = self._close(oldest_key, "evicted")
        self.evicted_count += 1
        if flow is not None:
            self._emit(flow)

    def _emit(self, flow: Flow) -> None:
        if self.on_flow_complete is None:
            return
        try:
            self.on_flow_complete(flow)
        except Exception:  # never let a consumer kill the capture thread
            logger.exception("on_flow_complete callback raised")

    # -------------------------------------------------------------- status
    @property
    def active_flows(self) -> int:
        with self._lock:
            return len(self._flows)

    def snapshot(self) -> list[dict[str, Any]]:
        with self._lock:
            return [flow.identity() for flow in self._flows.values()]

    def stats(self) -> dict[str, int]:
        with self._lock:
            return {
                "packets": self.packet_count,
                "active_flows": len(self._flows),
                "completed_flows": self.completed_count,
                "evicted_flows": self.evicted_count,
                "discarded_flows": self.discarded_count,
            }

    def add_packets(self, packets: Iterable[PacketInfo]) -> list[Flow]:
        """Convenience bulk ingest, used by the PCAP reader and the tests."""
        completed: list[Flow] = []
        for packet in packets:
            flow = self.add_packet(packet)
            if flow is not None:
                completed.append(flow)
        return completed


